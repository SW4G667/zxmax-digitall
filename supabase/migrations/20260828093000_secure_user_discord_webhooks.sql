GRANT EXECUTE ON FUNCTION public.claim_user_discord_webhook_delivery(uuid, uuid, text, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.complete_user_discord_webhook_delivery(uuid, text, text, integer, numeric) TO service_role;
