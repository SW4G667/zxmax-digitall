CREATE OR REPLACE FUNCTION public.sync_product_inventory_stock(_product_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  prod public.products%ROWTYPE;
  variation jsonb;
  next_variations jsonb := '[]'::jsonb;
  available_count integer;
  total_stock integer := 0;
  variation_stock integer;
  variation_id_value text;
  variation_delivery text;
BEGIN
  SELECT * INTO prod
  FROM public.products
  WHERE id = _product_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  IF jsonb_typeof(COALESCE(prod.variations, '[]'::jsonb)) = 'array'
     AND jsonb_array_length(COALESCE(prod.variations, '[]'::jsonb)) > 0 THEN
    FOR variation IN
      SELECT value FROM jsonb_array_elements(prod.variations)
    LOOP
      variation_id_value := NULLIF(btrim(variation->>'id'), '');
      variation_delivery := COALESCE(NULLIF(variation->>'deliveryType', ''), prod.delivery_type, 'manual');

      IF prod.inventory_mode = 'items'
         AND variation_delivery = 'auto'
         AND variation_id_value IS NOT NULL THEN
        SELECT count(*)::integer INTO available_count
        FROM public.product_inventory_items
        WHERE product_id = _product_id
          AND variation_id = variation_id_value
          AND status = 'available';

        variation := jsonb_set(variation, '{stock}', to_jsonb(available_count), true);
        variation_stock := available_count;
      ELSE
        variation_stock := CASE
          WHEN COALESCE(variation->>'stock', '') ~ '^\d+$'
            THEN GREATEST((variation->>'stock')::integer, 0)
          ELSE 0
        END;
      END IF;

      total_stock := total_stock + variation_stock;
      next_variations := next_variations || jsonb_build_array(variation);
    END LOOP;

    UPDATE public.products
    SET variations = next_variations,
        stock = total_stock,
        updated_at = now()
    WHERE id = _product_id;
  ELSIF prod.inventory_mode = 'items' AND prod.delivery_type = 'auto' THEN
    SELECT count(*)::integer INTO available_count
    FROM public.product_inventory_items
    WHERE product_id = _product_id
      AND variation_id IS NULL
      AND status = 'available';

    UPDATE public.products
    SET stock = available_count,
        updated_at = now()
    WHERE id = _product_id;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.sync_product_inventory_stock(bigint) FROM PUBLIC, anon, authenticated;

