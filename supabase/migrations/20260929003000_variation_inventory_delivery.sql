CREATE TABLE IF NOT EXISTS public.product_inventory_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  variation_id text,
  seller_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  content text NOT NULL,
  status text NOT NULL DEFAULT 'available',
  purchase_id bigint REFERENCES public.purchases(id) ON DELETE SET NULL,
  reserved_until timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  delivered_at timestamptz,
  CONSTRAINT product_inventory_items_content_check
    CHECK (char_length(btrim(content)) BETWEEN 1 AND 8000),
  CONSTRAINT product_inventory_items_status_check
    CHECK (status IN ('available', 'reserved', 'delivered'))
);

CREATE INDEX IF NOT EXISTS product_inventory_available_idx
  ON public.product_inventory_items(product_id, variation_id, status, id);

CREATE INDEX IF NOT EXISTS product_inventory_purchase_idx
  ON public.product_inventory_items(purchase_id)
