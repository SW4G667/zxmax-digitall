CREATE UNIQUE INDEX IF NOT EXISTS withdrawals_idempotency_key_uidx ON public.withdrawals(idempotency_key);

CREATE TABLE IF NOT EXISTS public.withdrawal_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  withdrawal_id bigint NOT NULL REFERENCES public.withdrawals(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  actor_id uuid,
  note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.withdrawal_events TO authenticated;
GRANT ALL ON public.withdrawal_events TO service_role;
ALTER TABLE public.withdrawal_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Owner and admins can view withdrawal events" ON public.withdrawal_events;
