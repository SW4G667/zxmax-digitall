-- Creating a listing requires a verified phone number. Admin/service operations
-- remain possible so moderation/import tools are not blocked.
CREATE OR REPLACE FUNCTION public.enforce_listing_phone_verification()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  verified_at timestamptz;
BEGIN
  IF current_user IN ('postgres','service_role','supabase_admin') THEN
    RETURN NEW;
  END IF;
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Faça login para anunciar.' USING ERRCODE = '42501';
  END IF;
  IF public.has_role(auth.uid(), 'admin'::public.app_role) THEN
    RETURN NEW;
  END IF;
  SELECT phone_verified_at INTO verified_at
  FROM public.profiles
  WHERE user_id = auth.uid();
  IF verified_at IS NULL THEN
    RAISE EXCEPTION 'Verifique seu número por SMS antes de anunciar.' USING ERRCODE = '42501';
  END IF;
  IF NEW.seller_id IS DISTINCT FROM auth.uid() THEN
    RAISE EXCEPTION 'Vendedor inválido.' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS enforce_listing_phone_verification_trg ON public.products;
CREATE TRIGGER enforce_listing_phone_verification_trg
BEFORE INSERT ON public.products
FOR EACH ROW EXECUTE FUNCTION public.enforce_listing_phone_verification();

