CREATE OR REPLACE FUNCTION public.notification_allowed(_user_id uuid, _channel text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    (
      SELECT enabled AND CASE _channel
        WHEN 'sales' THEN sales
        WHEN 'questions' THEN questions
        WHEN 'orders' THEN orders
        WHEN 'notices' THEN notices
        WHEN 'support' THEN support
        ELSE true
      END
      FROM public.notification_preferences
      WHERE user_id = _user_id
    ),
    true
  );
$$;

CREATE OR REPLACE FUNCTION public.push_notification(
  _user_id uuid,
  _type text,
  _title text,
  _body text,
  _href text,
  _channel text,
  _dedupe_key text DEFAULT NULL,
  _metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF _user_id IS NULL OR NOT public.notification_allowed(_user_id, _channel) THEN
    RETURN;
  END IF;
  INSERT INTO public.notifications(user_id,type,title,body,href,dedupe_key,metadata)
  VALUES (_user_id, left(_type,60), left(_title,120), left(coalesce(_body,''),500), left(_href,300), _dedupe_key, coalesce(_metadata,'{}'::jsonb))
  ON CONFLICT (dedupe_key) WHERE dedupe_key IS NOT NULL DO NOTHING;
END;
$$;

CREATE OR REPLACE FUNCTION public.notify_purchase_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  status_changed boolean := TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM NEW.status;
BEGIN
  IF NOT status_changed THEN RETURN NEW; END IF;

  IF NEW.status = 'paid' THEN
    PERFORM public.push_notification(NEW.seller_id,'sale','Nova venda confirmada','O pedido #'||NEW.id||' foi pago.','/minhas-compras?scope=sales&order='||NEW.id,'sales','sale:'||NEW.id||':paid',jsonb_build_object('orderId',NEW.id));
    PERFORM public.push_notification(NEW.buyer_id,'order','Pagamento confirmado','O pagamento do pedido #'||NEW.id||' foi confirmado.','/minhas-compras?scope=purchases&order='||NEW.id,'orders','buyer:'||NEW.id||':paid',jsonb_build_object('orderId',NEW.id));
  ELSIF NEW.status = 'delivered_pending_confirmation' THEN
    PERFORM public.push_notification(NEW.buyer_id,'order','Pedido marcado como entregue','Confira o pedido #'||NEW.id||' e confirme o recebimento.','/minhas-compras?scope=purchases&order='||NEW.id,'orders','buyer:'||NEW.id||':delivery',jsonb_build_object('orderId',NEW.id));
  ELSIF NEW.status = 'delivered' THEN
    PERFORM public.push_notification(NEW.buyer_id,'order','Pedido concluído','O pedido #'||NEW.id||' foi concluído.','/minhas-compras?scope=purchases&order='||NEW.id,'orders','buyer:'||NEW.id||':done',jsonb_build_object('orderId',NEW.id));
    PERFORM public.push_notification(NEW.seller_id,'sale','Pedido concluído','O pedido #'||NEW.id||' foi concluído. O saldo será liberado na data informada.','/minhas-compras?scope=sales&order='||NEW.id,'sales','seller:'||NEW.id||':done',jsonb_build_object('orderId',NEW.id));
  ELSIF NEW.status = 'dispute' THEN
    PERFORM public.push_notification(NEW.seller_id,'order','Disputa aberta','Uma disputa foi aberta no pedido #'||NEW.id||'.','/minhas-compras?scope=sales&order='||NEW.id,'orders','seller:'||NEW.id||':dispute',jsonb_build_object('orderId',NEW.id));
    PERFORM public.push_notification(NEW.buyer_id,'order','Disputa aberta','A disputa do pedido #'||NEW.id||' foi registrada.','/minhas-compras?scope=purchases&order='||NEW.id,'orders','buyer:'||NEW.id||':dispute',jsonb_build_object('orderId',NEW.id));
  ELSIF NEW.status IN ('refunded','cancelled') THEN
    PERFORM public.push_notification(NEW.buyer_id,'order',CASE WHEN NEW.status='refunded' THEN 'Pedido reembolsado' ELSE 'Pedido cancelado' END,'Atualização no pedido #'||NEW.id||'.','/minhas-compras?scope=purchases&order='||NEW.id,'orders','buyer:'||NEW.id||':'||NEW.status,jsonb_build_object('orderId',NEW.id));
    PERFORM public.push_notification(NEW.seller_id,'sale',CASE WHEN NEW.status='refunded' THEN 'Reembolso concluído' ELSE 'Pedido cancelado' END,'Atualização no pedido #'||NEW.id||'.','/minhas-compras?scope=sales&order='||NEW.id,'sales','seller:'||NEW.id||':'||NEW.status,jsonb_build_object('orderId',NEW.id));
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS notify_purchase_change_trg ON public.purchases;
CREATE TRIGGER notify_purchase_change_trg
AFTER INSERT OR UPDATE OF status ON public.purchases
FOR EACH ROW EXECUTE FUNCTION public.notify_purchase_change();

