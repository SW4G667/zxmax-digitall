CREATE OR REPLACE FUNCTION public.wallet_available_balance(_user_id uuid)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  sales numeric := 0;
  ledger numeric := 0;
  reserved numeric := 0;
BEGIN
  SELECT COALESCE(SUM(COALESCE(product_amount, GREATEST(amount-COALESCE(buyer_fee,0),0))),0)
    INTO sales
  FROM public.purchases
  WHERE seller_id=_user_id
    AND seller_released=true
    AND status='delivered'
    AND (released_at IS NULL OR released_at <= now());

  SELECT COALESCE(SUM(amount),0) INTO ledger
  FROM public.wallet_ledger
  WHERE user_id=_user_id AND available_at<=now();

  SELECT COALESCE(SUM(amount),0) INTO reserved
  FROM public.withdrawals
  WHERE user_id=_user_id
    AND status IN ('pending','approved')
    AND method <> 'admin_fee';

  RETURN GREATEST(0, ROUND(sales + ledger - reserved,2));
END;
$$;

CREATE OR REPLACE FUNCTION public.withdrawable_balance(_user_id uuid, _exclude_id bigint DEFAULT NULL)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  balance numeric := 0;
  excluded numeric := 0;
BEGIN
  balance := public.wallet_available_balance(_user_id);
  IF _exclude_id IS NOT NULL THEN
    SELECT COALESCE(amount,0) INTO excluded
    FROM public.withdrawals
    WHERE id=_exclude_id AND user_id=_user_id AND status IN ('pending','approved');
  END IF;
  RETURN ROUND(balance + excluded,2);
END;
$$;

-- Payment application: seller funds are held for the configured period.
CREATE OR REPLACE FUNCTION public.apply_verified_payment_v2(_provider text, _event_key text, _event_type text, _purchase_id bigint, _charge_id text, _confirmed_amount numeric, _payload jsonb DEFAULT '{}'::jsonb)
RETURNS TABLE(applied boolean, resulting_status text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
declare
  purchase_row public.purchases%rowtype;
  product_row public.products%rowtype;
  delivery_text text;
  next_status text := 'paid';
  next_messages jsonb;
  qty numeric := 1;
  expected_charge text;
  settings jsonb := '{}'::jsonb;
  release_days integer := 7;
begin
  if current_user not in ('postgres', 'service_role', 'supabase_admin') then raise exception 'server_only'; end if;

  insert into public.payment_events(provider,event_key,event_type,purchase_id,charge_id,amount,payload)
  values (_provider,_event_key,_event_type,_purchase_id,_charge_id,_confirmed_amount,coalesce(_payload,'{}'::jsonb))
  on conflict (provider,event_key) do nothing;
  if not found then
    select p.status into resulting_status from public.purchases p where p.id=_purchase_id;
    applied:=false; return next; return;
  end if;

  select * into purchase_row from public.purchases where id=_purchase_id for update;
  if not found then raise exception 'purchase_not_found'; end if;
  if purchase_row.status <> 'pending' then resulting_status:=purchase_row.status; applied:=false; return next; return; end if;

  expected_charge:=coalesce(purchase_row.provider_payment_id,purchase_row.evopay_charge_id);
  if expected_charge is distinct from _charge_id then raise exception 'charge_mismatch'; end if;
  if round(purchase_row.amount*100) is distinct from round(_confirmed_amount*100) then raise exception 'amount_mismatch'; end if;

  select * into product_row from public.products where id=purchase_row.product_id for update;
  if not found then raise exception 'product_not_found'; end if;

  SELECT value INTO settings FROM public.app_settings WHERE key='platform';
  release_days:=GREATEST(5,LEAST(7,COALESCE((settings->>'seller_release_days')::integer,7)));

  next_messages:=coalesce(purchase_row.messages,'[]'::jsonb);
  qty:=coalesce(purchase_row.quantity,1);

  if product_row.delivery_type='auto' then
    select delivery_content into delivery_text from public.product_delivery where product_id=purchase_row.product_id;
    if coalesce(delivery_text,'')<>'' then
      next_status:='delivered';
      next_messages:=next_messages||jsonb_build_array(jsonb_build_object('from','System','text','📦 ENTREGA_AUTO: '||delivery_text,'date',now()));
    end if;
  end if;

  update public.purchases
  set status=next_status,
      payment_status='paid',
      paid_at=coalesce(paid_at,now()),
      funds_available_at=coalesce(funds_available_at,now() + make_interval(days=>release_days)),
      seller_released=false,
      messages=next_messages,
      updated_at=now()
  where id=_purchase_id;

  update public.products
  set sales=coalesce(sales,0)+1,
      stock=case when stock is null then null else greatest(stock-greatest(qty,1),0) end
  where id=purchase_row.product_id;

  applied:=true; resulting_status:=next_status; return next;
end;
$$;

-- Completion and fund release are separate: delivery may finish before money is released.
CREATE OR REPLACE FUNCTION public.process_auto_release_orders()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  r record;
  processed integer := 0;
BEGIN
  -- Preserve the existing buyer-confirmation timeout, but do not release money early.
  UPDATE public.purchases
  SET status='delivered', updated_at=now(),
      messages=coalesce(messages,'[]'::jsonb)||jsonb_build_array(jsonb_build_object(
        'from','System','text','⏰ Pedido concluído automaticamente após o prazo de confirmação do comprador. O saldo continua seguindo o prazo de segurança da carteira.','date',now()
      ))
  WHERE status='delivered_pending_confirmation'
    AND delivered_pending_at IS NOT NULL
    AND delivered_pending_at <= now()-interval '3 days';

  FOR r IN
    SELECT id,seller_id FROM public.purchases
    WHERE status='delivered'
      AND seller_released=false
      AND funds_available_at IS NOT NULL
      AND funds_available_at<=now()
      AND payment_status='paid'
    FOR UPDATE
  LOOP
    UPDATE public.purchases
    SET seller_released=true,released_at=now(),updated_at=now(),
        messages=coalesce(messages,'[]'::jsonb)||jsonb_build_array(jsonb_build_object(
          'from','System','text','💰 Saldo da venda liberado na carteira após o período de segurança.','date',now()
        ))
    WHERE id=r.id;
    PERFORM public.push_notification(r.seller_id,'sale','Saldo liberado','O saldo do pedido #'||r.id||' já está disponível na carteira.','/sacar','sales','seller:'||r.id||':released',jsonb_build_object('orderId',r.id));
    processed:=processed+1;
  END LOOP;
  RETURN processed;
END;
$$;

-- Existing already-paid rows receive a deterministic 7-day hold date.
UPDATE public.purchases
SET funds_available_at = COALESCE(paid_at,created_at) + interval '7 days'
WHERE payment_status='paid' AND funds_available_at IS NULL;

-- Atomic wallet payment. Requires full document verification.
CREATE OR REPLACE FUNCTION public.pay_purchase_with_wallet(_purchase_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  p public.purchases%rowtype;
  prod public.products%rowtype;
  prof public.profiles%rowtype;
  bal numeric;
  delivery_text text;
  next_status text := 'paid';
  next_messages jsonb;
  settings jsonb := '{}'::jsonb;
  release_days integer := 7;
  qty numeric := 1;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Não autenticado'; END IF;
  PERFORM pg_advisory_xact_lock(hashtext(auth.uid()::text));

  SELECT * INTO prof FROM public.profiles WHERE user_id=auth.uid();
  IF prof IS NULL OR prof.verification_status <> 'approved' THEN
    RAISE EXCEPTION 'Verifique seus documentos antes de usar o saldo da carteira.';
  END IF;

  SELECT * INTO p FROM public.purchases WHERE id=_purchase_id FOR UPDATE;
  IF p IS NULL OR p.buyer_id<>auth.uid() THEN RAISE EXCEPTION 'Pedido não encontrado'; END IF;
  IF p.status<>'pending' THEN RAISE EXCEPTION 'Este pedido não está aguardando pagamento'; END IF;
  IF p.payment_provider<>'wallet' THEN RAISE EXCEPTION 'Forma de pagamento inválida'; END IF;

  bal:=public.wallet_available_balance(auth.uid());
  IF bal < p.amount THEN RAISE EXCEPTION 'Saldo da carteira insuficiente'; END IF;

  INSERT INTO public.wallet_ledger(user_id,amount,kind,purchase_id,description,dedupe_key)
  VALUES(auth.uid(),-p.amount,'purchase',p.id,'Compra do pedido #'||p.id,'wallet:purchase:'||p.id);

  SELECT * INTO prod FROM public.products WHERE id=p.product_id FOR UPDATE;
  IF prod IS NULL THEN RAISE EXCEPTION 'Produto indisponível'; END IF;

  SELECT value INTO settings FROM public.app_settings WHERE key='platform';
  release_days:=GREATEST(5,LEAST(7,COALESCE((settings->>'seller_release_days')::integer,7)));
  qty:=coalesce(p.quantity,1);
  next_messages:=coalesce(p.messages,'[]'::jsonb);

  IF prod.delivery_type='auto' THEN
    SELECT delivery_content INTO delivery_text FROM public.product_delivery WHERE product_id=p.product_id;
    IF coalesce(delivery_text,'')<>'' THEN
      next_status:='delivered';
      next_messages:=next_messages||jsonb_build_array(jsonb_build_object('from','System','text','📦 ENTREGA_AUTO: '||delivery_text,'date',now()));
    END IF;
  END IF;

  UPDATE public.purchases
  SET status=next_status,payment_status='paid',provider_payment_id='wallet:'||id,
      paid_at=now(),funds_available_at=now()+make_interval(days=>release_days),
      seller_released=false,messages=next_messages,updated_at=now()
  WHERE id=p.id;

  UPDATE public.products
  SET sales=coalesce(sales,0)+1,
      stock=case when stock is null then null else greatest(stock-greatest(qty,1),0) end
  WHERE id=p.product_id;

  RETURN jsonb_build_object('success',true,'status',next_status,'balance',public.wallet_available_balance(auth.uid()));
END;
$$;
GRANT EXECUTE ON FUNCTION public.pay_purchase_with_wallet(bigint) TO authenticated;

-- Seller-initiated refund goes to the buyer's ZXMAX wallet while funds are held.
CREATE OR REPLACE FUNCTION public.refund_purchase_to_wallet(_purchase_id bigint, _reason text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  p public.purchases%rowtype;
  is_admin boolean := false;
  clean_reason text := btrim(coalesce(_reason,''));
  qty numeric := 1;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Não autenticado'; END IF;
  SELECT * INTO p FROM public.purchases WHERE id=_purchase_id FOR UPDATE;
  IF p IS NULL THEN RAISE EXCEPTION 'Pedido não encontrado'; END IF;
  SELECT public.has_role(auth.uid(),'admin'::public.app_role) INTO is_admin;
  IF auth.uid()<>p.seller_id AND NOT is_admin THEN RAISE EXCEPTION 'Apenas o vendedor ou um administrador pode reembolsar'; END IF;
  IF p.status IN ('pending','refunded','cancelled') THEN RAISE EXCEPTION 'Este pedido não pode ser reembolsado neste estado'; END IF;
  IF char_length(clean_reason)<10 THEN RAISE EXCEPTION 'Informe um motivo com pelo menos 10 caracteres'; END IF;
  IF p.seller_released AND NOT is_admin THEN
    RAISE EXCEPTION 'O saldo desta venda já foi liberado. Abra uma disputa administrativa para concluir o reembolso.';
  END IF;

  INSERT INTO public.wallet_ledger(user_id,amount,kind,purchase_id,description,dedupe_key)
  VALUES(p.buyer_id,p.amount,'refund',p.id,'Reembolso do pedido #'||p.id,'wallet:refund:'||p.id);

  qty:=coalesce(p.quantity,1);
  UPDATE public.products
  SET stock=case when stock is null then null else stock+greatest(qty,1) end
  WHERE id=p.product_id;

  UPDATE public.purchases
